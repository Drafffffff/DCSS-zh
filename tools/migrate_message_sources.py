#!/usr/bin/env python3
"""Inventory fixed message producers; apply reviewed stable-ID replacements."""
import hashlib,json,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1];SRC=ROOT/'native/crawl-ref/source';LOC=ROOT/'localization/migration'
MODULES=('player','delay','shopping','skills','skill-menu','directn','quiver','describe','attack','melee-attack')
TOKEN=re.compile(r'//[^\n]*|/\*.*?\*/|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|\b(?:mprf|mpr)\s*\(',re.S)
LITERAL=re.compile(r'\s*(?:"(?:\\.|[^"\\])*"\s*)+$')
def literal(text):
    if not LITERAL.fullmatch(text):return None
    return ''.join(json.loads(s) for s in re.findall(r'"(?:\\.|[^"\\])*"',text))
def calls(text):
    for found in TOKEN.finditer(text):
        token=found.group()
        if not token.startswith(('mpr(', 'mpr ', 'mprf(', 'mprf ')):continue
        at=found.end();start=at;args=[];depth=0
        while at<len(text):
            match=re.match(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|/\*.*?\*/|//[^\n]*',text[at:],re.S)
            if match:at+=match.end();continue
            c=text[at]
            if c in '([{':depth+=1
            elif c in ')]}':
                if c==')' and depth==0:
                    args.append(text[start:at]);yield found.start(),at+1,token.split('(')[0].strip(),args;break
                depth-=1
            elif c==',' and depth==0:args.append(text[start:at]);start=at+1
            at+=1

def candidates():
    # Reuse complete existing translations as review material; Luna owns final prose.
    catalog=(SRC/'zh-catalog.inc').read_text()
    translations={json.loads(a):json.loads(b) for a,b in re.findall(r'\{("(?:\\.|[^"\\])*"),\s*("(?:\\.|[^"\\])*")\}',catalog)}
    result={}
    for module in MODULES:
        path=SRC/(module+'.cc')
        if not path.exists():continue
        text=path.read_text()
        for start,end,fn,args in calls(text):
            if len(args) not in (1,2):continue
            en=literal(args[-1])
            if en is None or re.search(r'%(?!%)',en):continue
            if len(args)==2 and (fn!='mprf' or not re.fullmatch(r'\s*MSGCH_[A-Z_]+\s*',args[0])):continue
            if not en.strip():continue
            identity='log.'+module.replace('-','_')+'.fixed.'+hashlib.sha256(en.encode()).hexdigest()[:12]
            if identity in result:continue
            result[identity]={'id':identity,'context':'Fixed message generated by '+module+'.cc','en':en,'zh':translations.get(en,en),'params':{},'source':{'file':module+'.cc','anchor':text[start:end],'line':text.count('\n',0,start)+1}}
    return list(result.values())

if __name__=='__main__':
    import argparse
    p=argparse.ArgumentParser();p.add_argument('--apply',action='store_true');a=p.parse_args()
    entries=candidates()
    if not a.apply:
        (LOC/'fixed-source-candidates.json').write_text(json.dumps({'messages':entries},ensure_ascii=False,indent=2)+'\n');print(len(entries),'fixed producer candidates')
    else:
        reviewed=json.loads((LOC/'luna-fixed-messages.json').read_text());by_source={(e['source']['file'],e['en']):e for e in reviewed['messages']}
        changed=0
        for module in MODULES:
            path=SRC/(module+'.cc')
            if not path.exists():continue
            text=path.read_text();edits=[]
            for start,end,fn,args in calls(text):
                en=literal(args[-1]);entry=by_source.get((path.name,en))
                if entry is None:continue
                if len(args)==1:channel=''
                elif len(args)==2 and fn=='mprf' and re.fullmatch(r'\s*MSGCH_[A-Z_]+\s*',args[0]):channel=', '+args[0].strip()
                else:continue
                edits.append((start,end,'mpr(zh_message('+json.dumps(entry['id'])+')'+channel+')'))
            for start,end,replacement in reversed(edits):text=text[:start]+replacement+text[end:]
            if edits:
                if '#include "zh-message.h"' not in text:text=text.replace('#include "AppHdr.h"','#include "AppHdr.h"\n#include "zh-message.h"',1)
                path.write_text(text);changed+=len(edits)
        print('Migrated',changed,'fixed producers')
